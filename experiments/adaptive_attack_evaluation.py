def evaluate_adaptive_attack(proxy_classifier, target_classifier, config):
    """
    Evaluate the performance of the target classifier against an adaptive attack
    that uses the proxy classifier to generate adversarial examples.

    It is based on the evaluation method of track 1, but with the addition of an adaptive attack that generates
    adversarial examples using the proxy classifier. The results are returned in the same format as the original
    evaluation method, but with additional entries for the adversarial examples generated by the attack.

    Parameters
    ----------
    proxy_classifier : DeepTrust
        The proxy classifier used to generate adversarial examples.
    target_classifier : DeepTrust
        The target classifier to be evaluated against the adaptive attack.
    config : config
        The configuration object containing the paths to the datasets and other parameters.

    Returns
    -------
    results : list of dict
        A list of dictionaries containing the evaluation results for the target classifier,
        including the predictions and scores for the original test sets and the adversarial
        examples generated by the attack.
    """

    results = []

    features_fp_check = load_features(config.FEATURES_TS_FP_CHECK)
    y_pred, scores = target_classifier.predict(features_fp_check)

    results.append({
        sha256: [int(y), float(s)] for sha256, y, s in zip(
            load_sha256_list(config.FEATURES_TS_FP_CHECK),
            y_pred, scores)})

    malware_features = load_features(config.FEATURES_TS_ADV)
    y_pred, scores = target_classifier.predict(malware_features)

    results.append({
        sha256: [int(y), float(s)] for sha256, y, s in zip(
            load_sha256_list(config.FEATURES_TS_ADV),
            y_pred, scores)})

    attack = FeatureSpaceAttack(classifier=proxy_classifier,
                                logging_level=logging.INFO)

    y_tr = load_labels(config.FEATURES_TR, config.TR)

    for n_feats in [25, 50, 100]:
        goodware_features = (
            sample for sample, label in zip(load_features(
            config.FEATURES_TR), y_tr) if label == 0)
        malware_features = load_features(config.FEATURES_TS_ADV)
        adv_examples = attack.run(
            malware_features, goodware_features, n_iterations=100,
            n_features=n_feats, n_candidates=50)
        y_pred, scores = target_classifier.predict(adv_examples)
        results.append({
            sha256: [int(y), float(s)] for sha256, y, s in zip(
                load_sha256_list(config.FEATURES_TS_ADV),
                y_pred, scores)})

    return results

if __name__ == "__main__":

    parser = argparse.ArgumentParser(description="Evaluate inference cost for specific models.")
    parser.add_argument(
        "--use_isolation_forest_in_ensemble",
        action="store_true",
        help="Configure the proxy classifier to use isolation forest for the ensemble (True) or not (False)."
    )
    args = parser.parse_args()

    proxy_classifier = DeepTrust.load(
        vectorizer_path="android-detectors/pretrained/deeptrust_vectorizer.pkl",
        classifier_path="android-detectors/pretrained/deeptrust_classifier.pkl")
    proxy_classifier.multistep = False # Turn into ensemble
    proxy_classifier.use_inspectRF_in_ensemble = args.use_isolation_forest_in_ensemble

    target_classifier = DeepTrust.load(
        vectorizer_path="android-detectors/pretrained/deeptrust_vectorizer.pkl",
        classifier_path="android-detectors/pretrained/deeptrust_classifier.pkl")

    results = evaluate_adaptive_attack(
        proxy_classifier=proxy_classifier,
        target_classifier=target_classifier,
        config=config
    )

    # Create directory for saving model and results
    path = f"experiments/out/adaptive_attack_{'with_if' if args.use_isolation_forest_in_ensemble else 'without_if'}"
    os.makedirs(path, exist_ok=True)
    # Save in json
    with open(f"{path}/evaluation.json", "w") as f:
        json.dump(results, f)
